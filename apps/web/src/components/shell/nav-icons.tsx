const made = new Map<string, NavIcon>();

/**
 * A tree icon drawn like an Ant Design icon: 1em square in a `span.anticon`, so it sits in menus, buttons and the sidebar
 * beside antd's own icons and takes their size and colour from the text around it.
 */
export function navIcon(name: string): NavIcon {
  let icon = made.get(name);
  if (!icon) {
    const Lucide = NAV_ICONS[name] ?? LayoutDashboardIcon;
    icon = function TreeIcon({ className, ...rest }: { className?: string; 'aria-hidden'?: boolean }) {
      return (
        <span aria-hidden className={className ? `anticon ${className}` : 'anticon'} {...rest}>
          <Lucide size="1em" strokeWidth={2} aria-hidden focusable={false} />
        </span>
      );
    };
    made.set(name, icon);
  }
  return icon;
}

/** A tree icon by name, as a component of its own (for a list of nodes drawn in one render). */
export function TreeIcon({ name, className }: { name: string; className?: string }) {
  const Lucide = NAV_ICONS[name] ?? LayoutDashboardIcon;
  return (
    <span aria-hidden className={className ? `anticon ${className}` : 'anticon'}>
      <Lucide size="1em" strokeWidth={2} aria-hidden focusable={false} />
    </span>
  );
}

